CREATE TABLE IF NOT EXISTS vets (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name TEXT,
  last_name  TEXT
);
CREATE INDEX IF NOT EXISTS idx_vets_last_name ON vets (last_name);

CREATE TABLE IF NOT EXISTS specialties (
  id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT
);
CREATE INDEX IF NOT EXISTS idx_specialties_name ON specialties (name);

CREATE TABLE IF NOT EXISTS vet_specialties (
  vet_id       INT NOT NULL REFERENCES vets (id),
  specialty_id INT NOT NULL REFERENCES specialties (id),
  UNIQUE (vet_id, specialty_id)
);

CREATE TABLE IF NOT EXISTS types (
  id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT
);
CREATE INDEX IF NOT EXISTS idx_types_name ON types (name);

CREATE TABLE  if not exists source_types(
                            id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            name VARCHAR(80)
);

CREATE TABLE IF NOT EXISTS owners (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name TEXT,
  last_name  TEXT,
  address    TEXT,
  city       TEXT,
  telephone  TEXT
);
CREATE INDEX IF NOT EXISTS idx_owners_last_name ON owners (last_name);

CREATE TABLE IF NOT EXISTS pets (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT,
  premisa     TEXT,
  birth_date DATE,
  type_id    INT REFERENCES types (id),
  owner_id   INT REFERENCES owners (id)
);
CREATE INDEX IF NOT EXISTS idx_pets_name ON pets (name);
CREATE INDEX IF NOT EXISTS idx_pets_owner_id ON pets (owner_id);
CREATE UNIQUE INDEX IF NOT EXISTS unique_owner_pet_name ON pets (owner_id, LOWER(name));

CREATE TABLE IF NOT EXISTS visits (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id      INT REFERENCES pets (id),
  visit_date  DATE,
  description TEXT,
  premise     TEXT,
  predicate   TEXT
);
CREATE INDEX IF NOT EXISTS idx_visits_pet_id ON visits (pet_id);

CREATE TABLE IF NOT EXISTS users (
                                   id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   name       VARCHAR(255),
                                   email VARCHAR(255) NOT NULL UNIQUE,
                                   provider VARCHAR(255),
                                   providerId VARCHAR(255),
                                   language VARCHAR(10),
                                   created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS cases (
                     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                     name       VARCHAR(255),
                     email VARCHAR(30),
                    user_id INTEGER references users(id)
);

CREATE INDEX IF NOT EXISTS cases_name ON cases (name);
CREATE TABLE IF NOT EXISTS arguments (
                         id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         name       VARCHAR(255),
                         premise       VARCHAR(255),
                         predicate       VARCHAR(255),
                         warrant       VARCHAR(255),
                         ordering    INTEGER,
                         type_id    INTEGER references types(id),
                         source_id  INTEGER references source_types(id) DEFAULT 0,
                         case_id   INTEGER references cases(id),
                         parent_id INTEGER references arguments(id),
                         user_id INTEGER references users(id)
);
CREATE TABLE IF NOT EXISTS evaluations (
                           id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           verification_status VARCHAR(30),
                           intensity  VARCHAR(30),
                           argument_id INTEGER references arguments(id),
                           user_id INTEGER references users(id)
);
create table IF NOT EXISTS ARGUMENT_TYPES (
                              ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              NAME VARCHAR(255)
);
CREATE SEQUENCE if not exists id_seq START WITH 100 INCREMENT BY 1;



CREATE INDEX IF NOT EXISTS user_email ON cases (email);

CREATE TABLE IF NOT EXISTS roles
(
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(30)
);

CREATE TABLE if not exists user_roles (
                                        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        user_id BIGINT NOT NULL,
                                        role_id BIGINT NOT NULL,
                                        case_id BIGINT NOT NULL,
                                        UNIQUE (user_id, role_id, case_id),
                                        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
                                        FOREIGN KEY (role_id) REFERENCES roles(id) ON DELETE CASCADE,
                                        FOREIGN KEY (case_id)  REFERENCES cases(id) on DELETE CASCADE
);

CREATE SEQUENCE if not exists audits_seq START WITH 100 INCREMENT BY 1;

CREATE TABLE if not exists audits (
                                        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        email VARCHAR(30),
                                        login_time TIMESTAMP
);

